"""Build paper/refs.bib from the BibTeX blocks in notes/<citekey>.md.

Only notes whose first line does not contain UNVERIFIED are included. The entry key is
renamed to the note's citekey; field values are copied from the note (fetched records),
with only mechanical normalisation: Unicode en dash in page ranges -> '--', and the
Crossref-style one-line entries reflowed. Run: .venv/bin/python notes/_work/build_bib.py
"""
import glob
import os
import re

SKIP = {"related_work"}
out, skipped = [], []
for f in sorted(glob.glob("notes/*.md")):
    key = os.path.basename(f)[:-3]
    if key in SKIP:
        continue
    text = open(f, encoding="utf-8").read()
    first = text.splitlines()[0] if text else ""
    if "UNVERIFIED" in first:
        skipped.append((key, "UNVERIFIED"))
        continue
    m = re.search(r"```(?:bibtex|bib)?\n(@.*?)```", text, re.S)
    if not m:
        skipped.append((key, "no BibTeX block"))
        continue
    # take only the first entry in the block (xu2021generalised lists PMLR then arXiv)
    block = m.group(1).strip()
    entries = re.split(r"\n(?=@)", block)
    entry = entries[0].strip()
    entry = re.sub(r"^@(\w+)\{[^,]*,", lambda mm: f"@{mm.group(1).lower()}{{{key},", entry, count=1)
    entry = entry.replace("–", "--")
    out.append(entry)

# Manual, documented additions that are not in the fetched records are NOT made here.
with open("paper/refs.bib", "w", encoding="utf-8") as fh:
    fh.write("% Generated by notes/_work/build_bib.py from verified notes/*.md entries.\n")
    fh.write("% Do not edit by hand; edit the note and rerun.\n\n")
    fh.write("\n\n".join(out) + "\n")
print(f"{len(out)} entries written; skipped: {skipped}")
