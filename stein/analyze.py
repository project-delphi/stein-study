"""P2 analysis: per-config means with seed-level 95% bootstrap CIs, and hypothesis contrasts.

    .venv/bin/python -m stein.analyze [--held results/heldout.parquet] [--tune results/tuning.parquet]

Writes results/summary.parquet (one row per config), results/contrasts.parquet (one row per
contrast), results/tables/*.md, and results/analysis.md. No numbers are typed by hand.

Bootstrap: 10000 resamples of seeds (percentile CI). A contrast A - B resamples A's and B's
seeds independently (different arms do not share randomness, so the seeds are not paired).
"""
import argparse, json, os
import numpy as np
import pandas as pd

KEYS = ["tier", "arm", "d", "sigma", "alpha", "law", "prior", "lam", "ema_tau"]
METRICS = ["content_r2", "content_knn_r2", "leak_r2", "leak_knn_r2", "ident_orth_r2", "shape_acc", "class_acc",
           "eff_rank", "emb_std_mean", "gauss_ep_raw", "ksd_prior", "npksd_prior", "loss_cv_last20"]
B = 10000
RNG = np.random.default_rng(20261108)
GT = ["sigreg", "sksd", "ksd", "mmd"]          # isotropic-Gaussian-target regularisers
NAMES = dict(none="none", vicreg="VICReg", sigreg="SIGReg", sksd="sliced KSD", ksd="KSD", mmd="MMD",
             ema="EMA", oracle="oracle")


def boot_mean(x):
    x = np.asarray(x, float); x = x[np.isfinite(x)]
    if len(x) == 0:
        return np.nan, np.nan, np.nan, 0
    m = RNG.choice(x, (B, len(x))).mean(1)
    return x.mean(), np.percentile(m, 2.5), np.percentile(m, 97.5), len(x)


def boot_diff(a, b):
    a = np.asarray(a, float); b = np.asarray(b, float); a = a[np.isfinite(a)]; b = b[np.isfinite(b)]
    if len(a) == 0 or len(b) == 0:
        return np.nan, np.nan, np.nan
    da = RNG.choice(a, (B, len(a))).mean(1) - RNG.choice(b, (B, len(b))).mean(1)
    return a.mean() - b.mean(), np.percentile(da, 2.5), np.percentile(da, 97.5)


def boot_did(a1, a0, b1, b0):
    """(a1 - a0) - (b1 - b0): difference in differences (interaction)."""
    if min(len(a1), len(a0), len(b1), len(b0)) == 0:
        return np.nan, np.nan, np.nan
    r = lambda x: RNG.choice(np.asarray(x, float), (B, len(x))).mean(1)
    est = (np.mean(a1) - np.mean(a0)) - (np.mean(b1) - np.mean(b0))
    bs = (r(a1) - r(a0)) - (r(b1) - r(b0))
    return est, np.percentile(bs, 2.5), np.percentile(bs, 97.5)


def load(path):
    df = pd.read_parquet(path)
    df["ema_tau"] = np.where(df["arm"].str.startswith("ema"), df["ema_tau"], np.nan)
    df["lam"] = df["lam"].astype(float)
    for m in METRICS:
        if m not in df:
            df[m] = np.nan
    return df


def sel(df, **kw):
    q = df
    for k, v in kw.items():
        q = q[q[k] == v]
    return q


def summarise(df):
    rows = []
    for key, g in df.groupby(KEYS, dropna=False):
        r = dict(zip(KEYS, key)); r["n_seeds"] = g["seed"].nunique()
        for m in METRICS:
            mu, lo, hi, n = boot_mean(g[m])
            r[m], r[m + "_lo"], r[m + "_hi"] = mu, lo, hi
        r["collapsed_frac"] = float((g["emb_std_mean"] < 0.01).mean())
        rows.append(r)
    return pd.DataFrame(rows)


def fmt(m, lo, hi, p=3):
    if not np.isfinite(m):
        return "–"
    return f"{m:.{p}f} [{lo:.{p}f}, {hi:.{p}f}]"


def verdict_sign(lo, hi):
    if not (np.isfinite(lo) and np.isfinite(hi)):
        return "n/a"
    return "+" if lo > 0 else ("−" if hi < 0 else "0")


class Out:
    def __init__(self):
        self.md, self.con = [], []

    def h(self, s):
        self.md.append(f"\n## {s}\n")

    def p(self, s):
        self.md.append(s)

    def table(self, rows, cols):
        self.md.append("| " + " | ".join(cols) + " |")
        self.md.append("|" + "---|" * len(cols))
        for r in rows:
            self.md.append("| " + " | ".join(str(x) for x in r) + " |")
        self.md.append("")

    def contrast(self, hyp, label, metric, est, lo, hi):
        self.con.append(dict(hyp=hyp, label=label, metric=metric, est=est, lo=lo, hi=hi, sign=verdict_sign(lo, hi)))
        return [label, metric, fmt(est, lo, hi), verdict_sign(lo, hi)]


def shapes_base(df, **kw):
    base = dict(tier="shapes", d=12, sigma=0.0, alpha=1.0, law="uniform", prior="gaussian")
    base.update(kw)
    return sel(df, **base)


def arm_metric_table(o, S, rowkey, rowvals, arms, metrics, extra=None):
    cols = [rowkey, "arm"] + metrics + ["n"]
    rows = []
    for v in rowvals:
        for a in arms:
            g = sel(S, **{rowkey: v}, arm=a, **(extra or {}))
            if len(g) == 0:
                continue
            g = g.iloc[0]
            rows.append([v, NAMES.get(a, a)] + [fmt(g[m], g[m + "_lo"], g[m + "_hi"]) for m in metrics] + [g["n_seeds"]])
    o.table(rows, cols)


def run(held, tune):
    o = Out()
    os.makedirs("results/tables", exist_ok=True)
    o.p("# P2 analysis (generated by `python -m stein.analyze`; do not edit by hand)\n")
    o.p("Means over held-out seeds with 95% percentile bootstrap CIs over seeds (10000 resamples). "
        "Contrast sign: + / − = CI excludes 0, 0 = CI includes 0.\n")

    if tune is not None:
        T = load(tune)
        St = summarise(T)
        o.h("Tuning (validation seeds 100, 101): leakage vs λ at the tuning settings")
        rows = []
        for _, r in St.sort_values(["tier", "law", "prior", "arm", "lam", "ema_tau"]).iterrows():
            rows.append([r.tier, r.law, r.prior, NAMES.get(r.arm, r.arm), r.lam if not r.arm.startswith("ema") or r.arm != "ema" else f"τ={r.ema_tau}",
                         f"{r.content_r2:.3f}" if np.isfinite(r.content_r2) else f"acc {r.class_acc:.3f}",
                         f"{r.leak_r2:.3f}", f"{r.leak_knn_r2:.3f}" if np.isfinite(r.leak_knn_r2) else "–"])
        o.table(rows, ["tier", "law", "prior", "arm", "λ / τ", "content R² (val)", "leak R²", "kNN leak R²"])
        St.to_parquet("results/tuning_summary.parquet", index=False)

    if held is None or not os.path.exists(held):
        return o
    D = load(held)
    S = summarise(D)
    S.to_parquet("results/summary.parquet", index=False)
    o.p(f"Held-out runs: {len(D)} ({D['seed'].nunique()} seeds: {sorted(D['seed'].unique().tolist())}); configs: {len(S)}.\n")
    M = ["content_r2", "leak_r2", "leak_knn_r2", "ident_orth_r2", "eff_rank", "emb_std_mean"]

    # ---------------------------------------------------------------- H1
    o.h("H1: dimension d (k = 6) × arms, 3DShapes, α = 1, σ = 0, uniform law")
    S1 = sel(S, tier="shapes", sigma=0.0, alpha=1.0, law="uniform", prior="gaussian")
    arm_metric_table(o, S1, "d", [3, 6, 12, 24], ["none", "vicreg", "sigreg", "sksd", "ksd", "mmd", "ema", "oracle"], M)
    rows = []
    for d in [3, 6, 12, 24]:
        for a in GT:
            for ref in ["vicreg", "ema"]:
                for m in ["leak_r2", "leak_knn_r2"]:
                    A = shapes_base(D, d=d, arm=a)[m]; R = shapes_base(D, d=d, arm=ref)[m]
                    rows.append([d] + o.contrast("H1", f"d={d}: {NAMES[a]} − {NAMES[ref]}", m, *boot_diff(A, R)))
    o.p("Contrasts (leakage, arm − reference):\n")
    o.table(rows, ["d", "contrast", "metric", "estimate [95% CI]", "sign"])

    # ---------------------------------------------------------------- H2
    o.h("H2: information bottleneck σ × d ∈ {12, 24}")
    arms2 = ["ema", "vicreg"] + GT
    for d in [12, 24]:
        o.p(f"\nd = {d}:\n")
        arm_metric_table(o, sel(S, tier="shapes", alpha=1.0, law="uniform", prior="gaussian", d=d), "sigma", [0.0, 0.5, 1.0], arms2,
                         ["content_r2", "leak_r2", "leak_knn_r2", "content_knn_r2"])
    rows = []
    for a in arms2:
        for m in ["leak_r2", "leak_knn_r2", "content_r2"]:
            for d in [12, 24]:
                for s in [0.5, 1.0]:
                    rows.append(o.contrast("H2", f"{NAMES[a]} d={d}: σ={s} − σ=0", m,
                                           *boot_diff(shapes_base(D, d=d, sigma=s, arm=a)[m], shapes_base(D, d=d, arm=a)[m])))
            for dl in [3, 6]:
                rows.append(o.contrast("H2", f"{NAMES[a]} σ=0: d={dl} − d=24", m,
                                       *boot_diff(shapes_base(D, d=dl, arm=a)[m], shapes_base(D, d=24, arm=a)[m])))
    o.p("Contrasts (σ effect at fixed d; d effect at σ = 0):\n")
    o.table(rows, ["contrast", "metric", "estimate [95% CI]", "sign"])

    # ---------------------------------------------------------------- H3
    o.h("H3: content law × regulariser (identifiability = ident_orth_r2)")
    S3 = sel(S, tier="shapes", d=12, sigma=0.0, alpha=1.0)
    rows = []
    for law in ["uniform", "gaussian", "laplace"]:
        for a in GT + ["oracle"]:
            for prior in ["gaussian", "uniform", "laplace"]:
                g = sel(S3, law=law, arm=a, prior=prior)
                if len(g) == 0 or (a == "oracle" and prior != "gaussian"):
                    continue
                g = g.iloc[0]
                rows.append([law, NAMES[a], prior + (" (matched)" if prior == law else ""), f"{g.lam:g}",
                             fmt(g.ident_orth_r2, g.ident_orth_r2_lo, g.ident_orth_r2_hi),
                             fmt(g.content_r2, g.content_r2_lo, g.content_r2_hi),
                             fmt(g.leak_r2, g.leak_r2_lo, g.leak_r2_hi),
                             fmt(g.npksd_prior, g.npksd_prior_lo, g.npksd_prior_hi), g.n_seeds])
    o.table(rows, ["law", "arm", "prior", "λ", "ident R²", "content R²", "leak R²", "NP-KSD to prior", "n"])
    rows = []
    for law in ["uniform", "laplace", "gaussian"]:
        for ma in ["ksd", "sksd"]:
            if law == "gaussian" and ma == "sksd":
                continue
            A = sel(D, tier="shapes", d=12, sigma=0.0, alpha=1.0, law=law, arm=ma, prior=law)
            for b in GT + ["oracle"]:
                if law == "gaussian" and b == "ksd":
                    continue
                Bq = sel(D, tier="shapes", d=12, sigma=0.0, alpha=1.0, law=law, arm=b, prior="gaussian")
                for m in ["ident_orth_r2", "content_r2"]:
                    rows.append([law] + o.contrast("H3", f"law={law}: {NAMES[ma]}(matched) − {NAMES[b]}", m, *boot_diff(A[m], Bq[m])))
    o.p("Contrasts (matched-prior arm − Gaussian-target arm or oracle):\n")
    o.table(rows, ["law", "contrast", "metric", "estimate [95% CI]", "sign"])

    # ---------------------------------------------------------------- H4
    o.h("H4: nuisance strength α × arms (d = 12)")
    arms4 = ["ema", "vicreg"] + GT
    arm_metric_table(o, sel(S, tier="shapes", d=12, sigma=0.0, law="uniform", prior="gaussian"), "alpha", [0.0, 0.5, 1.0], arms4,
                     ["content_r2", "leak_r2", "leak_knn_r2", "eff_rank"])
    rows = []
    for m in ["leak_r2", "leak_knn_r2", "content_r2"]:
        for a in arms4:
            rows.append(o.contrast("H4", f"{NAMES[a]}: α=1 − α=0", m,
                                   *boot_diff(shapes_base(D, alpha=1.0, arm=a)[m], shapes_base(D, alpha=0.0, arm=a)[m])))
        for a in arms4[1:]:
            rows.append(o.contrast("H4", f"interaction: (EMA α1−α0) − ({NAMES[a]} α1−α0)", m,
                                   *boot_did(shapes_base(D, alpha=1.0, arm="ema")[m], shapes_base(D, alpha=0.0, arm="ema")[m],
                                             shapes_base(D, alpha=1.0, arm=a)[m], shapes_base(D, alpha=0.0, arm=a)[m])))
    o.table(rows, ["contrast", "metric", "estimate [95% CI]", "sign"])

    # ---------------------------------------------------------------- H5
    o.h("H5: temporal tier (3DShapes clips, T = 3, α = 1, d = 12)")
    ST = sel(S, tier="temporal")
    tarms = ["ema", "ema+sksd", "ema+sigreg", "sksd", "vicreg"]
    arm_metric_table(o, ST, "tier", ["temporal"], tarms, M)
    rows = []
    for m in ["leak_r2", "leak_knn_r2"]:
        E = sel(D, tier="temporal", arm="ema")[m]
        for a in ["sksd", "vicreg"]:
            rows.append(o.contrast("H5", f"EMA − {NAMES[a]} (alone)", m, *boot_diff(E, sel(D, tier="temporal", arm=a)[m])))
        for a in ["ema+sksd", "ema+sigreg"]:
            rows.append(o.contrast("H5", f"{a} − EMA", m, *boot_diff(sel(D, tier="temporal", arm=a)[m], E)))
    o.table(rows, ["contrast", "metric", "estimate [95% CI]", "sign"])

    # ---------------------------------------------------------------- CIFAR
    o.h("Natural-image tier (CIFAR-10, α = 1, d = 12)")
    arm_metric_table(o, sel(S, tier="cifar"), "tier", ["cifar"], ["none", "vicreg", "sigreg", "sksd", "ksd", "mmd", "ema"],
                     ["class_acc", "leak_r2", "eff_rank", "emb_std_mean"])
    rows = []
    for m in ["leak_r2", "class_acc"]:
        for a in GT:
            for ref in ["vicreg", "ema"]:
                rows.append(o.contrast("CIFAR", f"{NAMES[a]} − {NAMES[ref]}", m,
                                       *boot_diff(sel(D, tier="cifar", arm=a)[m], sel(D, tier="cifar", arm=ref)[m])))
    o.table(rows, ["contrast", "metric", "estimate [95% CI]", "sign"])

    # ---------------------------------------------------------------- H6
    o.h("H6: VAE tier (3DShapes, d = 12) vs JEPA arms at d = 12")
    SV = sel(S, tier="vae")
    rows = []
    for _, g in SV.sort_values(["law", "prior", "arm"]).iterrows():
        rows.append([g.law, g.prior, {"betavae": "β-VAE", "ksd": "KSD-AE", "mmd": "MMD-AE"}[g.arm], f"{g.lam:g}"] +
                    [fmt(g[m], g[m + "_lo"], g[m + "_hi"]) for m in ["content_r2", "leak_r2", "leak_knn_r2", "ident_orth_r2"]] + [g.n_seeds])
    o.table(rows, ["law", "prior", "arm", "λ/β", "content R²", "leak R²", "kNN leak R²", "ident R²", "n"])
    rows = []
    jepa = ["vicreg", "sigreg", "sksd", "ksd", "mmd", "ema", "oracle"]
    for m in ["leak_r2", "leak_knn_r2"]:
        for va in ["betavae", "ksd", "mmd"]:
            V = sel(D, tier="vae", arm=va, law="uniform", prior="gaussian")[m]
            for a in jepa:
                rows.append(o.contrast("H6", f"{va}-AE − JEPA {NAMES[a]}", m, *boot_diff(V, shapes_base(D, arm=a)[m])))
    for m in ["ident_orth_r2", "content_r2"]:
        rows.append(o.contrast("H6", "KSD-AE Laplace law: matched (Laplace) prior − Gaussian prior", m,
                               *boot_diff(sel(D, tier="vae", arm="ksd", law="laplace", prior="laplace")[m],
                                          sel(D, tier="vae", arm="ksd", law="laplace", prior="gaussian")[m])))
    o.table(rows, ["contrast", "metric", "estimate [95% CI]", "sign"])

    # ---------------------------------------------------------------- λ sensitivity (held-out seeds)
    if os.path.exists("results/lam_sens.parquet"):
        L = load("results/lam_sens.parquet")
        SL = summarise(L)
        SL.to_parquet("results/lam_sens_summary.parquet", index=False)
        o.h("H1 robustness: λ sensitivity at the base setting (d = 12, held-out seeds 1–5)")
        o.p("All three tuning levels of each regulariser, on held-out seeds (`python -m stein.sweep lam_sens`). "
            "The selected level is the H1 run.\n")
        rows = []
        for _, g in SL.sort_values(["arm", "lam"]).iterrows():
            rows.append([NAMES[g.arm], f"{g.lam:g}"] + [fmt(g[m], g[m + "_lo"], g[m + "_hi"])
                        for m in ["content_r2", "leak_r2", "leak_knn_r2", "ident_orth_r2"]] + [g.n_seeds])
        o.table(rows, ["arm", "λ", "content R²", "leak R²", "kNN leak R²", "ident R²", "n"])
        rows = []
        for a in ["vicreg"] + GT + ["oracle"]:
            lams = sorted(sel(L, arm=a)["lam"].unique())
            for m in ["leak_r2", "leak_knn_r2"]:
                rows.append(o.contrast("H1-lam", f"{NAMES[a]}: λ={lams[-1]:g} − λ={lams[0]:g}", m,
                                       *boot_diff(sel(L, arm=a, lam=lams[-1])[m], sel(L, arm=a, lam=lams[0])[m])))
        vic = sel(L, arm="vicreg")
        vic_min = min(vic["lam"].unique(), key=lambda l: sel(vic, lam=l)["leak_r2"].mean())
        E = shapes_base(D, arm="ema")
        for a in GT:
            for l in sorted(sel(L, arm=a)["lam"].unique()):
                A = sel(L, arm=a, lam=l)
                for m in ["leak_r2", "leak_knn_r2"]:
                    rows.append(o.contrast("H1-lam", f"{NAMES[a]} λ={l:g} − VICReg λ={vic_min:g} (its least-leaky level)", m,
                                           *boot_diff(A[m], sel(vic, lam=vic_min)[m])))
                    rows.append(o.contrast("H1-lam", f"{NAMES[a]} λ={l:g} − EMA", m, *boot_diff(A[m], E[m])))
        o.table(rows, ["contrast", "metric", "estimate [95% CI]", "sign"])

    # ---------------------------------------------------------------- stability / collapse
    o.h("Collapse and loss stability (all held-out configs)")
    bad = S[(S.collapsed_frac > 0) | (S.loss_cv_last20 > 0.5)]
    rows = [[r.tier, r.arm, r.d, r.sigma, r.alpha, r.law, r.prior, f"{r.collapsed_frac:.2f}", f"{r.loss_cv_last20:.3f}"]
            for _, r in bad.iterrows()]
    o.table(rows, ["tier", "arm", "d", "σ", "α", "law", "prior", "collapsed fraction", "loss CV (last 20%)"])
    nf = int((D.get("loss_nonfinite", pd.Series(0)) > 0).sum())
    o.p(f"Runs with any non-finite loss: {nf}.\n")
    return o


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--held", default="results/heldout.parquet")
    ap.add_argument("--tune", default="results/tuning.parquet")
    a = ap.parse_args()
    o = run(a.held, a.tune if os.path.exists(a.tune) else None)
    open("results/analysis.md", "w").write("\n".join(o.md) + "\n")
    if o.con:
        pd.DataFrame(o.con).to_parquet("results/contrasts.parquet", index=False)
    print(f"wrote results/analysis.md ({len(o.md)} lines), {len(o.con)} contrasts")


if __name__ == "__main__":
    main()
