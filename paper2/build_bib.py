"""Build paper2/refs.bib from the verified BibTeX blocks in notes/<citekey>.md.

Only the keys cited in paper2/paper.qmd are written. The rules are the same as
notes/_work/build_bib.py (which writes study 1's paper/refs.bib and is left untouched): notes whose
first line contains UNVERIFIED are refused, the first entry of the note's BibTeX block is copied with its
key renamed to the citekey, en dashes become '--', and bare month macros are braced.

One manual entry is added: the companion study (study 1 of this repository, paper/paper.pdf), which is
a local report rather than a published paper, so it has no note. It is labelled as such in the entry.

Run: .venv/bin/python paper2/build_bib.py
"""
import os
import re
import sys

QMD, OUT = "paper2/paper.qmd", "paper2/refs.bib"
COMPANION = """@misc{kalia2026dimension,
  author = {Kalia, Ravi},
  title = {Dimension, not noise: what limits nuisance leakage in regularised {JEPAs}},
  year = {2026},
  howpublished = {Companion study (study 1), unpublished report, \\texttt{paper/paper.pdf} in this repository}
}"""

text = open(QMD, encoding="utf-8").read()
keys = sorted(set(re.findall(r"@([a-z][a-z0-9]+\d{4}[a-z]*)", text)))
out, missing = [], []
for key in keys:
    if key == "kalia2026dimension":
        out.append(COMPANION)
        continue
    f = f"notes/{key}.md"
    if not os.path.exists(f):
        missing.append((key, "no note"))
        continue
    note = open(f, encoding="utf-8").read()
    if "UNVERIFIED" in note.splitlines()[0]:
        missing.append((key, "UNVERIFIED"))
        continue
    m = re.search(r"```(?:bibtex|bib)?\n(@.*?)```", note, re.S)
    if not m:
        missing.append((key, "no BibTeX block"))
        continue
    entry = re.split(r"\n(?=@)", m.group(1).strip())[0].strip()
    entry = re.sub(r"^@(\w+)\{[^,]*,", lambda mm: f"@{mm.group(1).lower()}{{{key},", entry, count=1)
    entry = entry.replace("–", "--")
    entry = re.sub(r"(month\s*=\s*)([A-Za-z]+)(\s*,)", r"\1{\2}\3", entry)
    out.append(entry)

with open(OUT, "w", encoding="utf-8") as fh:
    fh.write("% Generated by paper2/build_bib.py from verified notes/*.md entries (+ the companion study).\n")
    fh.write("% Do not edit by hand; edit the note and rerun.\n\n")
    fh.write("\n\n".join(out) + "\n")
print(f"{len(out)} entries written to {OUT}; problems: {missing}")
sys.exit(1 if missing else 0)
